static void LM75B_ReadTemp(uint8_t *out) // T INTERNA
{
    uint8_t r1[2], r2[2];

    HAL_I2C_Mem_Read(&hi2c1, LM75_ADDR, LM75_TEMP_REGISTER, I2C_MEMADD_SIZE_8BIT, r1, 2, HAL_MAX_DELAY);
    HAL_I2C_Mem_Read(&hi2c1, LM75_ADDR, LM75_TEMP_REGISTER, I2C_MEMADD_SIZE_8BIT, r2, 2, HAL_MAX_DELAY);

    if (r1[0] != r2[0])
    {
        /* MSByte cambiato tra le due letture -> possibile "torn read",
           scarto entrambe e ne faccio una terza, ora "pulita" */
        HAL_I2C_Mem_Read(&hi2c1, LM75_ADDR, LM75_TEMP_REGISTER, I2C_MEMADD_SIZE_8BIT, out, 2, HAL_MAX_DELAY);
    }
    else
    {
        /* le due letture concordano -> il dato è coerente, uso la seconda */
        out[0] = r2[0];
        out[1] = r2[1];
    }
}

void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM3) // T INTERNA
    {
        uint8_t raw_bytes[2];
        int16_t raw;

        LM75B_ReadTemp(raw_bytes);

        /* raw_bytes[0]=MSB, raw_bytes[1]=LSB, entrambi uint8_t: nessuna
           estensione di segno indesiderata nella combinazione */
        raw = (int16_t)((raw_bytes[0] << 8) | raw_bytes[1]);
        raw >>= 7;                 /* i dati validi sono i 9 bit alti (D8..D0) */

        temp_int = raw * 0.5f;       /* LSB = 0.5 °C per l'LM75 */

        //len = sprintf((char*)tx_buf, "Temperature: %.3f °C\r\n", temp);
        //HAL_UART_Transmit_DMA(&huart2, tx_buf, len);

        ready_int=1;
    }
}
void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc) // T ESTERNA
{
	// Il Trigger (Timer 2 a 1Hz) avvia la conversione ogni secondo
	// Quando arriva l'EoC aggiorniamo i valori

	v_temp_sense_est = ((float)adc_buf * 3.3f) / 4095.0f;


	temp_est = ((v_temp_sense_est - 0.76f) / 0.0025f) + 25.0f;

	ready_est=1;

	// LCD

	sprintf(lcd_buffer_int, "Interna: %.1fC", temp_int);
	sprintf(lcd_buffer_est, "Esterna: %.1fC", temp_est);

	if(first_time){
		if(ready_int){
			lcd_println(lcd_buffer_int, 0);
			int_first = 1;

		}else if(ready_est){
			lcd_println(lcd_buffer_est, 0);
			est_first=1;
		}

		first_time=0;
		second_time=1;

	}else if(second_time){
		if(int_first){
			lcd_println(lcd_buffer_int, 0);
			lcd_println(lcd_buffer_est, 1);
		}else if(est_first){
			lcd_println(lcd_buffer_est, 0);
			lcd_println(lcd_buffer_int, 1);
		}
		second_time=0;
	}else{
		if(int_first){
			lcd_println(lcd_buffer_est, 0);
			lcd_println(lcd_buffer_int, 1);
			int_first=0;
			est_first=1;
		}
		else if(est_first){
			lcd_println(lcd_buffer_int, 0);
			lcd_println(lcd_buffer_est, 1);
			est_first=0;
			int_first=1;
		}
	}

}




