/* USER CODE BEGIN 0 */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
	if(htim->Instance == TIM2){ // 1Hz
		len = sprintf((char*)tx_buf, "Potentiometer: %.2f V\r\n", voltage);
		HAL_UART_Transmit_DMA(&huart2, tx_buf, len);

		// Riarmare l'ADC
		HAL_ADC_Start_IT(&hadc1);

	}

	if(htim->Instance == TIM3){ // la frequenza dipende
		ticks+=1;
		if(ticks==duration_note){
			i+=1;
			if(i==sizeof(Swan_Lake)/sizeof(Swan_Lake[0])){ // Fine Canzone
				i=0;

			}
			play_note(Swan_Lake[i].Period, Swan_Lake[i].Duration);
	}
}
}

void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc)
{
    // Quando arriva l'EoC aggiorniamo il valore
	adc_value = HAL_ADC_GetValue(hadc);
	voltage = ((float)adc_value * 3.3f) / 4095.0f;

	// Velocità canzone
	float perc=(voltage/2.0) + 0.5;
	int arr=(int)(8400/(perc*4) -1);
	__HAL_TIM_SET_AUTORELOAD(&htim3, arr);
}


void play_note(uint32_t Period, uint32_t Duration){
    duration_note=Duration;
    ticks=0;

	// Aggiorna il Periodo (frequenza) nel registro del Timer
    // L'unica variabile da ri-inizializzare è quella di base (più veloce di HAL_TIM_Base_Init)
    // Usiamo una macro veloce che accede direttamente al registro
    __HAL_TIM_SET_AUTORELOAD(&htim1, Period - 1);

    // Aggiorna il Pulse (Duty Cycle)
	__HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_2, Period / 2);



    // Fai suonare nota
	HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_2);
}


