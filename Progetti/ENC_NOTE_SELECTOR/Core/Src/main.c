void play_note(uint32_t Period, uint32_t Duration){
    //duration_note=Duration;
    ticks=0;

	// Aggiorna il Periodo (frequenza) nel registro del Timer
    // L'unica variabile da ri-inizializzare è quella di base (più veloce di HAL_TIM_Base_Init)
    // Usiamo una macro veloce che accede direttamente al registro
    __HAL_TIM_SET_AUTORELOAD(&htim1, Period - 1);

    // Aggiorna il Pulse (Duty Cycle)
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_2, Period / 2);



    // Fai suonare nota
	HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_2);
}
